  function kf(u, ch) {
    var n = ch.length, i = 0;
    u -= Math.floor(u);
    while (i < n && ch[i][0] <= u) i++;
    var a = ch[(i - 1 + n) % n], b = ch[i % n];
    var ua = a[0] - (i === 0 ? 1 : 0), ub = b[0] + (i === n ? 1 : 0);
    var t = ub > ua ? (u - ua) / (ub - ua) : 0;
    return a[1] + (b[1] - a[1]) * CURVA[b[2] || 'io'](t);
  }
