  function tensaoDe(forma, camada) { var v = MORFO.viva[forma + '/' + camada]; return v == null ? 1 / 6 : v; }

  function desenhaMorfo(h) {
    var ctx = h.ctx, cor = h.cor, M = h.p.morfo, a = FORMAS[M.a], b = FORMAS[M.b], m = M.m, mm = lim(m, 0, 1);
    MORFO.camadas.forEach(function (c) {
      var nome = c[0], n = c[1], k = c[2], A = a[nome], B = b[nome], pts = new Float32Array(A.length), i;
      for (i = 0; i < A.length; i++) pts[i] = A[i] + (B[i] - A[i]) * m;
      if (M.mexe) M.mexe(nome, pts, n);
      var tens = mix(tensaoDe(M.a, nome), tensaoDe(M.b, nome), mm);
      ctx.beginPath();
      for (i = 0; i < k; i++) liso(ctx, pts, i * n * 2, n, tens);
      if (c[4]) { ctx.lineWidth = c[4]; ctx.strokeStyle = cor.tinta; ctx.stroke(); }
      ctx.fillStyle = c[3] === 'papel' ? cor.papel : cor.tinta; ctx.fill();
    });
  }

  function desenhaLente(h, L, q) {
    var ctx = h.ctx, p = h.p;
    ctx.save();
    ctx.translate(L.jx, L.jy + q.y); ctx.rotate(q.rot * RAD); ctx.scale(q.sx, 1); ctx.translate(-L.jx, -L.jy);
    if (q.esc !== 1) { ctx.translate(L.cx, L.cy); ctx.scale(q.esc, q.esc); ctx.translate(-L.cx, -L.cy); }
    var pts = (q.fechar || q.feliz || q.sy !== 1) ? olho(L, q) : L.pts;
    trilha(ctx, pts); ctx.fillStyle = h.cor.tinta; ctx.fill();
    ctx.clip();
    if (h.A && h.A.lente) { ctx.save(); h.A.lente(h, L === LE ? 'e' : 'd', L); ctx.restore(); }
    var a = p.br.a * (1 - suave(0.1, 0.4, Math.max(q.fechar, Math.abs(q.feliz))));
    if (a > 0.01) { ctx.globalAlpha = a; ctx.translate(p.br.x, p.br.y); pinta(ctx, L.brilho, h.cor.papel); }
    ctx.restore();
  }

  function quadro(ctx, A, t, cor) {
    var p = novaPose(), q = novaPose(), u = 0;
    if (A) {
      t = ((t % A.ciclo) + A.ciclo) % A.ciclo; u = t / A.ciclo;
      A.pose(p, u, t);
      A.pose(q, u - 0.055 / A.ciclo, t - 0.055);          // a mesma pose, um instante antes: é o atraso dos óculos
    }
    var h = { ctx: ctx, cor: cor, p: p, u: u, t: t, A: A }, c = p.cab, o = p.oc;
    if (A && A.atras) A.atras(h);
    ctx.save();
    ctx.translate(256 + c.x, 300 + c.y); ctx.rotate(c.rot * RAD); ctx.scale(c.sx, c.sy); ctx.translate(-256, -300);
    var M = p.morfo;
    if (M && !(M.a === 'ganso' && M.m <= 0) && !(M.b === 'ganso' && M.m >= 1)) desenhaMorfo(h); else desenhaBico(h);
    if (A && A.rosto) A.rosto(h);                          // encaixe: entre o bico e os óculos
    ctx.save();
    ctx.translate(256 + o.x + (q.cab.x - c.x) * 0.85 * o.solto, 200 + o.y + (q.cab.y - c.y) * 0.85 * o.solto);
    ctx.rotate((o.rot + (q.cab.rot - c.rot) * 0.6 * o.solto) * RAD); ctx.translate(-256, -200);
    pinta(ctx, R.ponte, cor.tinta);
    desenhaLente(h, LE, p.le); desenhaLente(h, LD, p.ld);
    ctx.restore();
    if (A && A.cabeca) A.cabeca(h);                        // encaixe: na frente, acompanhando a cabeça
    ctx.restore();
    if (A && A.frente) A.frente(h);                        // encaixe: na frente de tudo, sem acompanhar a cabeça
  }

  /** Desenha um quadro. ctx: contexto 2d; nome: animação; t: segundos; opcoes: { tamanho, pb, cores }. */
  function desenhar(ctx, nome, t, opcoes) {
    var o = opcoes || {}, tam = o.tamanho || 512;
    ctx.save();
    ctx.scale(tam / 512, tam / 512);
    ctx.lineJoin = 'round'; ctx.lineCap = 'round';
    quadro(ctx, ANIMS[nome] || null, t || 0, o.cores || (o.pb ? CORES_PB : CORES));
    ctx.restore();
  }

